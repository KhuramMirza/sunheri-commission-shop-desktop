import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import bytenode from 'bytenode'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const OUT_MAIN_DIR = path.join(__dirname, 'out', 'main')
const CJS_FILE = path.join(OUT_MAIN_DIR, 'index.cjs')
const JSC_FILE = path.join(OUT_MAIN_DIR, 'index.jsc')
const ENTRY_LOADER_FILE = path.join(OUT_MAIN_DIR, 'entry.cjs')

async function compileBytecode() {
  console.log('\n===============================================================')
  console.log('       Compiling Main Process to V8 Bytecode (Bytenode)        ')
  console.log('===============================================================')

  if (!fs.existsSync(CJS_FILE)) {
    console.error(`[bytenode error] Could not find compiled CJS file at: ${CJS_FILE}`)
    console.error('Please run "electron-vite build" first.')
    process.exit(1)
  }

  console.log(`[bytenode] Compiling ${CJS_FILE} -> ${JSC_FILE}...`)

  try {
    // Compile to V8 bytecode using Electron's runtime V8 environment
    await bytenode.compileFile({
      filename: CJS_FILE,
      output: JSC_FILE,
      electron: true
    })

    const jscStats = fs.statSync(JSC_FILE)
    console.log(`[bytenode] Successfully created bytecode: ${JSC_FILE} (${jscStats.size} bytes)`)

    // Create the secure loader entry point
    const loaderContent = `// Auto-generated Bytenode Entry Loader for Soneri Commission Shop
const path = require('path')
const fs = require('fs')

const jscPath = path.join(__dirname, 'index.jsc')
const cjsPath = path.join(__dirname, 'index.cjs')

if (fs.existsSync(jscPath)) {
  // Production mode: Load compiled V8 bytecode (source protected)
  require('bytenode')
  require(jscPath)
} else if (fs.existsSync(cjsPath)) {
  // Development mode fallback
  require(cjsPath)
} else {
  throw new Error('Fatal: Main process bytecode not found at ' + jscPath)
}
`

    fs.writeFileSync(ENTRY_LOADER_FILE, loaderContent, 'utf-8')
    console.log(`[bytenode] Generated entry loader: ${ENTRY_LOADER_FILE}`)

    // Remove the raw JS/CJS source file so it cannot be extracted or decompiled from ASAR
    fs.unlinkSync(CJS_FILE)
    console.log(`[bytenode] Securely removed raw source file: ${CJS_FILE}`)

    // Clean any source map files if present
    const mapFile = CJS_FILE + '.map'
    if (fs.existsSync(mapFile)) {
      fs.unlinkSync(mapFile)
      console.log(`[bytenode] Removed source map: ${mapFile}`)
    }

    console.log('[bytenode] V8 bytecode compilation completed successfully!\n')
  } catch (err) {
    console.error('[bytenode] Compilation failed:', err)
    process.exit(1)
  }
}

compileBytecode()
